"""
Dataset and target-loading utilities for Evoscope morphology learning.

This module converts Evoscope morphology snapshots, saved as `grid_XXX.npy`
files, into one-hot encoded tensors suitable for convolutional neural
networks. It also aligns each morphology snapshot with either global
gene/protein summaries or flattened cluster-level gene/protein summaries.

The resulting `TorexDataset` provides a bridge between the simulated spatial
morphology and downstream machine-learning models, enabling latent-space
learning of tissue-like organization and its relationship to regulatory
dynamics.

Evoscope — minimal regulatory spatial model for emergent multicellular organization.

Author: Luca Zammataro
Organization: Lunan Foldomics LLC
"""


from __future__ import annotations

import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Tuple, Union

import numpy as np
import pandas as pd
import torch
from torch.utils.data import Dataset

PathLike = Union[str, os.PathLike]

GRID_VALUE_TO_CLASS = {
    -1: 0,  # empty
    0: 1,   # undetermined
    1: 2,   # cluster 0
    2: 3,   # cluster 1
    3: 4,   # cluster 2
    4: 5,   # cluster 3
    5: 6,   # cluster 4
    6: 7,   # cluster 5
    7: 8,   # cluster 6
    8: 9,   # cluster 7
}

N_CLASSES = 10
GLOBAL_GENES = ["T1", "T2", "I", "R", "M", "K", "S"]
CLUSTERS = list(range(8))
TARGET_MODES = {"global", "cluster_flat"}


@dataclass(frozen=True)
class SampleRecord:
    """One aligned morphology/target sample."""

    step: int
    snapshot_path: str
    target: np.ndarray


def parse_step_from_snapshot(path: PathLike) -> int:
    """Extract the simulation step from a snapshot filename such as ``grid_005.npy``."""

    m = re.search(r"grid_(\d+)\.npy$", os.path.basename(str(path)))
    if not m:
        raise ValueError(f"Cannot parse step from snapshot path: {path}")
    return int(m.group(1))


def list_snapshot_files(snapshots_dir: PathLike) -> List[Tuple[int, str]]:
    """Return sorted ``(step, path)`` pairs for Evoscope ``grid_*.npy`` snapshots."""

    snapshots_path = Path(snapshots_dir)
    if not snapshots_path.exists():
        raise FileNotFoundError(f"Snapshot directory does not exist: {snapshots_path}")

    files: List[Tuple[int, str]] = []
    for path in snapshots_path.iterdir():
        if not path.name.startswith("grid_") or path.suffix != ".npy":
            continue
        files.append((parse_step_from_snapshot(path), str(path)))

    files.sort(key=lambda x: x[0])
    return files


def load_global_targets(global_csv: PathLike) -> Dict[int, np.ndarray]:
    """Load global gene-expression targets indexed by simulation step."""

    df = pd.read_csv(global_csv)
    required = {"step", *GLOBAL_GENES}
    missing = required.difference(df.columns)
    if missing:
        raise ValueError(f"Missing columns in {global_csv}: {sorted(missing)}")

    targets: Dict[int, np.ndarray] = {}
    for _, row in df.iterrows():
        step = int(row["step"])
        targets[step] = row[GLOBAL_GENES].to_numpy(dtype=np.float32)
    return targets


def load_cluster_targets(cluster_csv: PathLike) -> Dict[int, np.ndarray]:
    """Load cluster-level gene-expression targets indexed by simulation step.

    Each target is flattened as ``8 clusters × 7 genes = 56`` values.
    """

    df = pd.read_csv(cluster_csv)
    required = {"step", "cluster", *GLOBAL_GENES}
    missing = required.difference(df.columns)
    if missing:
        raise ValueError(f"Missing columns in {cluster_csv}: {sorted(missing)}")

    targets: Dict[int, np.ndarray] = {}
    for step, sdf in df.groupby("step"):
        arr = np.zeros((len(CLUSTERS), len(GLOBAL_GENES)), dtype=np.float32)
        for _, row in sdf.iterrows():
            cid = int(row["cluster"])
            if cid not in CLUSTERS:
                continue
            arr[cid, :] = row[GLOBAL_GENES].to_numpy(dtype=np.float32)
        targets[int(step)] = arr.reshape(-1)
    return targets


def grid_to_class_map(grid: np.ndarray) -> np.ndarray:
    """Convert raw Evoscope grid values to contiguous class labels."""

    out = np.zeros_like(grid, dtype=np.int64)
    for raw_val, cls in GRID_VALUE_TO_CLASS.items():
        out[grid == raw_val] = cls
    return out


def class_map_to_onehot(cls_map: np.ndarray, n_classes: int = N_CLASSES) -> np.ndarray:
    """Convert a 2D class map into a ``C × H × W`` one-hot tensor array."""

    onehot = np.eye(n_classes, dtype=np.float32)[cls_map]  # H, W, C
    return np.transpose(onehot, (2, 0, 1))  # C, H, W


class TorexDataset(Dataset):
    """PyTorch dataset for Evoscope/TorHex morphology snapshots.

    Parameters
    ----------
    snapshots_dir:
        Directory containing ``grid_*.npy`` files.
    target_mode:
        ``"global"`` for global gene targets, or ``"cluster_flat"`` for flattened
        cluster-level targets.
    global_csv:
        CSV generated by ``save_global_gene_csv``. Required for ``target_mode="global"``.
    cluster_csv:
        CSV generated by ``save_cluster_gene_csv``. Required for ``target_mode="cluster_flat"``.
    """

    def __init__(
        self,
        snapshots_dir: PathLike,
        target_mode: str,
        global_csv: Optional[PathLike] = None,
        cluster_csv: Optional[PathLike] = None,
    ) -> None:
        if target_mode not in TARGET_MODES:
            raise ValueError(f"target_mode must be one of {sorted(TARGET_MODES)}")

        snapshot_files = list_snapshot_files(snapshots_dir)
        if not snapshot_files:
            raise FileNotFoundError(f"No grid_*.npy snapshots found in {snapshots_dir}")

        if target_mode == "global":
            if global_csv is None:
                raise ValueError("global_csv is required for target_mode='global'")
            target_map = load_global_targets(global_csv)
            self.target_dim = len(GLOBAL_GENES)
        else:
            if cluster_csv is None:
                raise ValueError("cluster_csv is required for target_mode='cluster_flat'")
            target_map = load_cluster_targets(cluster_csv)
            self.target_dim = len(CLUSTERS) * len(GLOBAL_GENES)

        records: List[SampleRecord] = []
        missing_steps: List[int] = []
        for step, path in snapshot_files:
            if step not in target_map:
                missing_steps.append(step)
                continue
            records.append(SampleRecord(step=step, snapshot_path=path, target=target_map[step]))

        if not records:
            raise RuntimeError("No aligned snapshot/target pairs found")

        self.records = records
        self.missing_steps = missing_steps
        self.target_mode = target_mode

        first_grid = np.load(self.records[0].snapshot_path)
        if first_grid.ndim != 2:
            raise ValueError("Snapshots must be 2D arrays")
        self.height, self.width = first_grid.shape

    def __len__(self) -> int:
        return len(self.records)

    def __getitem__(self, idx: int):
        rec = self.records[idx]
        grid = np.load(rec.snapshot_path)
        cls_map = grid_to_class_map(grid)
        x = class_map_to_onehot(cls_map)
        y = rec.target.astype(np.float32)
        return {
            "x": torch.from_numpy(x),
            "classes": torch.from_numpy(cls_map),
            "y": torch.from_numpy(y),
            "step": torch.tensor(rec.step, dtype=torch.int64),
        }
